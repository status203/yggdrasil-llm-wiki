#!/bin/sh
# Self-check for regen-views.sh. Builds a throwaway wiki, regenerates, and asserts the
# output. Runs the script in place against the wiki as its argument, and touches nothing
# outside its own temp directories.

set -eu
script=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/regen-views.sh
tmpfirst=$(mktemp)
W=$(mktemp -d)
wt=
trap 'rm -rf "$W" "$tmpfirst"; [ -z "$wt" ] || rm -rf "$wt"' EXIT

mkdir -p "$W/Food" "$W/Misc"
git -C "$W" init -q
git -C "$W" config user.email t@example.com
git -C "$W" config user.name t

page() { # page <wiki-relative path> <frontmatter body>
	mkdir -p "$(dirname "$W/$1")"
	{ echo '---'; printf '%s\n' "$2"; echo '---'; echo; echo body; } >"$W/$1"
}
regen() { sh "$script" "$W" "$@"; }

page Food/.subject.md 'role: instruction
pitch: Recipes and food knowledge.'
page Misc/.subject.md 'role: instruction
pitch: Items that do not yet justify a subject.'
page Food/Bread.md 'type: concept
pitch: How bread works.'
page "Food/Pipe | trouble.md" 'type: concept
pitch: A pitch with a | pipe in it.'
page Food/Old.md 'role: derived
pitch: Should be excluded.'
page 'Food/Bread recipes/Sourdough.md' 'type: recipe
pitch: A nested page.'
page Food/.templates/recipe.md 'type: reference
pitch: In a dotfolder.'
page 'Misc/Speaking practice.md' 'type: progression/practice
pitch: Speaking tracker.
progress: pausing for effect'
page 'Misc/Loose.md' 'pitch: A progression with no type.
progress: step one'
page Misc/.templates/practice.md 'type: progression/practice
progress: template placeholder'
printf 'progress: in a body with no frontmatter\n' >"$W/Misc/No frontmatter.md"
printf -- '---\npitch: Closed early.\n---\nprogress: after the frontmatter\n' >"$W/Misc/Body.md"
printf -- '--- \ntype: concept\npitch: Opens with a trailing space.\n---\n' >"$W/Food/Spaced.md"
: >"$W/Misc/Empty.md"

# Only a folder holding a .subject.md is a subject; a root-level file is no page.
page import/Stray.md 'type: progression/practice
pitch: Imported, not yet placed.
progress: unplaced progress'
printf '# Notes for the session\n\nprogress: at the root\n' >"$W/CLAUDE.md"

git -C "$W" add -A >/dev/null
git -C "$W" commit -qm seed

regen all >/dev/null

fail=0
pass() { echo "ok    — $1"; }
flop() { echo "FAIL  — $1"; fail=1; }
check() { # check <description> <file> <expected substring>
	if grep -Fq -- "$3" "$W/$2"; then pass "$1"; else flop "$1"; echo "        wanted: $3"; fi
}
refute() { if grep -Fq -- "$3" "$W/$2"; then flop "$1"; else pass "$1"; fi; }

check "wiki index links each subject" Index.md '| [[Food/Index\|Food]] | Recipes and food knowledge. |'
check "subject index lists a content page" Food/Index.md '| [[Bread]] | How bread works. |'
refute "role: derived page is excluded" Food/Index.md 'Should be excluded'
refute "the index does not list itself" Food/Index.md '[[Index]]'
check "a pipe in a pitch is escaped" Food/Index.md 'A pitch with a \| pipe in it.'
check "a pipe in a filename is escaped" Food/Index.md '[[Pipe \| trouble]]'
check "a nested page is listed by its subject-relative path" Food/Index.md '| [[Bread recipes/Sourdough]] | A nested page. |'
refute "a dotfolder page is excluded" Food/Index.md 'In a dotfolder.'
refute "a first line of \"--- \" opens no frontmatter (F15.2)" Food/Index.md 'Opens with a trailing space.'
check "progressions sit at the wiki root and strip the kind from the display name" Progressions.md '| practice | [[Speaking practice\|Speaking]] | pausing for effect |'
check "a progression with no type lists with an empty kind" Progressions.md '|  | [[Loose\|Loose]] | step one |'
refute "a progression in a dotfolder is excluded" Progressions.md 'template placeholder'
refute "progress: outside frontmatter is not read" Progressions.md 'in a body'
refute "progress: after the frontmatter closes is not read" Progressions.md 'after the frontmatter'
refute "an empty page does not list" Progressions.md '[[Empty'
check "every view stamps its date" Index.md "regenerated: $(date -u +%F)"
check "the note names the invocation" Index.md 'note: Regenerated by sh <program>/.yg/bin/regen-views.sh <wiki> wiki — edits'

if [ -e "$W/import/Index.md" ]; then flop "a folder with no .subject.md gets no index"; else pass "a folder with no .subject.md gets no index"; fi
refute "and is not listed as a subject" Index.md 'import'
refute "and its pages list nowhere" Progressions.md 'unplaced progress'
refute "a root-level file is not read as a page" Progressions.md 'at the root'
regen subjects >/dev/null
if [ -e "$W/import/Index.md" ]; then flop "subjects mode skips a folder with no .subject.md"; else pass "subjects mode skips a folder with no .subject.md"; fi
rc=0; regen subject import >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 2 ] && [ ! -e "$W/import/Index.md" ]; then pass "subject mode refuses a folder with no .subject.md"; else flop "subject mode refuses a folder with no .subject.md (exit $rc)"; fi

# Regenerating twice must not change anything — a view is a pure function of its inputs.
cp "$W/Food/Index.md" "$tmpfirst"
regen subjects >/dev/null
if cmp -s "$tmpfirst" "$W/Food/Index.md"; then pass "regeneration is idempotent"; else flop "regeneration is idempotent"; fi

# The date moves only with the content, so a regeneration that changes nothing else leaves
# no diff behind it.
sed 's/^regenerated: .*/regenerated: 2000-01-01/' "$W/Food/Index.md" >"$tmpfirst" && cp "$tmpfirst" "$W/Food/Index.md"
regen subjects >/dev/null
check "a view whose rows are unchanged keeps its date" Food/Index.md 'regenerated: 2000-01-01'
page Food/Salt.md 'type: concept
pitch: Why salt matters.'
regen subjects >/dev/null
check "a view whose rows changed takes today's date" Food/Index.md "regenerated: $(date -u +%F)"

# --- freshness -----------------------------------------------------------------
# Each of these caught a real defect during design: the deletion case (a delete leaves
# no newer file), publish() bumping the directory past the index it had just written,
# a wiki check at depth 1 firing on a page added inside a subject, and Progressions.md,
# published into the wiki root after the wiki index, restaling it on every run.
#
# age() dates every source 2019 and every view 2020 before a change, so the change is
# newer than the views it should restale even on a filesystem with coarse mtimes, and a
# view rewritten afterwards is newer than anything left at 2019 or 2020.

age() {
	find "$W" -name .git -prune -o -exec env TZ=UTC0 touch -t 201901010000 {} +
	for v in "$W/Index.md" "$W/Progressions.md" "$W"/*/Index.md; do
		[ -f "$v" ] && TZ=UTC0 touch -t 202001010000 "$v"
	done
	return 0
}
fresh() { # fresh <label> — asserts `stale` regenerates nothing
	out=$(regen stale)
	if [ -z "$out" ]; then pass "$1"; else flop "$1 (regenerated: $(echo $out))"; fi
}
stale() { # stale <label> <wiki-relative view expected to be rewritten>
	out=$(regen stale)
	if printf '%s\n' "$out" | grep -qxF "wrote $2"; then pass "$1"; else flop "$1 (regenerated: $(echo ${out:-nothing}))"; fi
}

regen all >/dev/null
fresh "a just-regenerated wiki is fresh"

# all writes the wiki index first and Progressions.md last, into the same directory. Dated
# back, the wiki index is older than that directory, as it is whenever the run spans a tick.
regen all >/dev/null
for s in "$W"/*/.subject.md; do TZ=UTC0 touch -t 201901010000 "$s"; done
TZ=UTC0 touch -t 202001010000 "$W/Index.md"
fresh "publishing Progressions.md after the wiki index leaves the wiki fresh"

age
echo x >>"$W/Food/Bread.md"
stale "a modified page restales its subject" "Food/Index.md"
fresh "and a second stale finds nothing — the progressions publish does not restale the wiki"

age
page Food/Cake.md 'type: concept
pitch: How cake works.'
stale "an added page restales its subject" "Food/Index.md"
fresh "and is fresh again once regenerated"

age
rm "$W/Food/Cake.md"
stale "a deleted page restales its subject" "Food/Index.md"
fresh "and is fresh again once regenerated"

age
rm "$W/Food/Bread recipes/Sourdough.md"
stale "a deleted nested page restales its subject" "Food/Index.md"
fresh "and is fresh again once regenerated"

age
page Chess/.subject.md 'role: instruction
pitch: Openings, endgames and study.'
stale "an added subject restales the wiki index" "Index.md"
fresh "and is fresh again once regenerated"

age
rm -rf "$W/Chess"
stale "a removed subject restales the wiki index" "Index.md"
fresh "and is fresh again once regenerated"

age
page Misc/.subject.md 'role: instruction
pitch: A changed pitch.'
stale "an edited .subject.md restales the wiki index" "Index.md"
fresh "and is fresh again once regenerated"

age
page import/Another.md 'type: concept
pitch: Also imported.'
fresh "a page added to a folder with no .subject.md restales nothing"

age
rm "$W/Progressions.md"
stale "a deleted Progressions.md is rewritten" "Progressions.md"
fresh "and is fresh again once regenerated"

# A page written during another writer's scan: a mktemp dating the scan's start to 2000
# makes every page, dated 2019, one that outran it. The view must keep that start as its
# stamp, or the next stale reads the page as already listed.
age
shim=$(mktemp -d)
printf '#!/bin/sh\nf=$(%s "$@") && TZ=UTC0 touch -t 200001010000 "$f" && echo "$f"\n' "$(command -v mktemp)" >"$shim/mktemp"
chmod +x "$shim/mktemp"
PATH="$shim:$PATH" regen subject Food >/dev/null
rm -rf "$shim"
stale "a page written during the scan restales its subject" "Food/Index.md"
fresh "and is fresh again once regenerated"

# The false positive that -maxdepth 1 would produce: page churn inside a subject must
# not restale the wiki index, which lists subjects and never pages.
age
page Misc/Thing.md 'type: concept
pitch: A thing.'
out=$(regen stale)
if printf '%s\n' "$out" | grep -qxF 'wrote Index.md'; then flop "a page added inside a subject leaves the wiki index alone"; else pass "a page added inside a subject leaves the wiki index alone"; fi

# Single-subject mode touches one index and no others.
regen all >/dev/null
echo y >>"$W/Food/Bread.md"
out=$(regen subject Food)
if printf '%s\n' "$out" | grep -qxF 'wrote Food/Index.md'; then pass "subject mode regenerates the named subject"; else flop "subject mode regenerates the named subject (got: ${out:-nothing})"; fi
if printf '%s\n' "$out" | grep -qxF 'wrote Misc/Index.md'; then flop "subject mode leaves other subjects alone"; else pass "subject mode leaves other subjects alone"; fi

# --check hands over to check-vault.sh once the stale views are written, keeping its exit.
page Food/Flawed.md 'type: concept
pitch: "unclosed'
rc=0; out=$(regen stale --check) || rc=$?
if [ "$rc" -eq 1 ] && printf '%s\n' "$out" | grep -qxF 'wrote Food/Index.md' && printf '%s\n' "$out" | grep -qF 'Food/Flawed.md'; then
	pass "stale --check writes the views, then reports check-vault's finding with its exit"
else flop "stale --check writes the views, then reports check-vault's finding with its exit (exit $rc: $out)"; fi
rm "$W/Food/Flawed.md"
rc=0; regen stale --chek >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 2 ]; then pass "a misspelt --check is a usage error"; else flop "a misspelt --check is a usage error (exit $rc)"; fi

# A linked worktree's files are all dated the checkout moment (`F22.4`), so a page it has not
# changed must take the main checkout's date, and one it has changed keeps its own.
TZ=UTC0 touch -t 202001010000 "$W/Misc/Speaking practice.md"
page 'Misc/Chess practice.md' 'type: progression/practice
pitch: Chess tracker.
progress: endgame drills'
TZ=UTC0 touch -t 202001010000 "$W/Misc/Chess practice.md"
git -C "$W" add -A >/dev/null
git -C "$W" commit -qm pages
wt=$(mktemp -d)
rmdir "$wt"
git -C "$W" worktree add -q "$wt" HEAD
echo more >>"$wt/Misc/Chess practice.md"
sh "$script" "$wt" progressions >/dev/null
if grep -Fq '[[Speaking practice\|Speaking]] | pausing for effect | 2020-01-01 |' "$wt/Progressions.md"; then
	pass "in a worktree an unchanged page takes the main checkout's date"
else flop "in a worktree an unchanged page takes the main checkout's date"; fi
if grep -Fq "[[Chess practice\|Chess]] | endgame drills | $(date -u +%F) |" "$wt/Progressions.md"; then
	pass "in a worktree a changed page keeps its own date"
else flop "in a worktree a changed page keeps its own date"; fi
git -C "$W" worktree remove --force "$wt"
wt=

# A download has no repository until /yg-init makes one, and the session-start hook runs first.
rm -rf "$W/.git"
rc=0; regen stale >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 0 ]; then pass "stale runs in a copy with no repository"; else flop "stale runs in a copy with no repository (exit $rc)"; fi

# The wiki root is the first argument, never found from the working directory.
rc=0; sh "$script" >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 2 ]; then pass "no wiki root is a usage error"; else flop "no wiki root is a usage error (exit $rc)"; fi
rc=0; out=$(sh "$script" "$W/nowhere" all 2>&1) || rc=$?
case "$rc $out" in "2 "*"no wiki at"*) pass "a wiki root that is no directory is refused" ;; *) flop "a wiki root that is no directory is refused (exit $rc)" ;; esac
rc=0; regen sideways >/dev/null 2>&1 || rc=$?
if [ "$rc" -eq 2 ]; then pass "an unknown mode is a usage error"; else flop "an unknown mode is a usage error (exit $rc)"; fi

# The shared awkward wiki (fixture-awkward-wiki.sh): every page reaches its subject's
# index, a case-only twin is linked by its path, and every link the views write is one
# check-vault.sh would not call over-qualified, so the two agree on which may be bare —
# in a UTF-8 locale and under LC_ALL=C, where an accented name cannot be counted (F19.3).
A=$(mktemp -d)
pages=$(sh "${script%/*}/fixture-awkward-wiki.sh" "$A")
for loc in "${LANG:-C.UTF-8}" C; do
	LC_ALL=$loc sh "$script" "$A" all >/dev/null
	missed=$(printf '%s\n' "$pages" | while IFS= read -r p; do
		n=${p#*/}; n=${n%.md}
		grep -qF -e "[[$n]]" -e "[[${p%.md}\\|$n]]" "$A/${p%%/*}/Index.md" || printf '%s; ' "$p"
	done)
	[ -z "$missed" ] && pass "every awkward page is in its subject's index ($loc)" || flop "awkward pages missing from an index ($loc): $missed"
	grep -qF '[[Cooking/Opening\|Opening]]' "$A/Cooking/Index.md" && grep -qF '[[Chess/opening\|opening]]' "$A/Chess/Index.md" &&
		pass "a case-only twin is linked by its path ($loc)" || flop "a case-only twin is linked by its path ($loc)"
	{ printf -- '---\ntype: concept\npitch: The views'"'"' links.\n---\n\n'; cat "$A"/*/Index.md | grep '^| \[\[' | sed 's/\\|/|/g'; } >"$A/Chess/Links.md"
	out=$(LC_ALL=$loc sh "${script%/*}/check-vault.sh" "$A" 2>&1 | grep 'qualified wikilink') || :
	rm "$A/Chess/Links.md"
	[ -z "$out" ] && pass "check-vault calls no view link over-qualified ($loc)" || flop "check-vault calls a view link over-qualified ($loc): $out"
done
printf -- '---\ntype: progression/tutorial\npitch: Opening a bottle of wine.\nprogress: step 1/3\n---\n\nBody.\n' >"$A/Cooking/Opening.md"
sh "$script" "$A" progressions >/dev/null
grep -qF '[[Cooking/Opening\|Opening]]' "$A/Progressions.md" && pass "a progression with a case-only twin is linked by its path" ||
	flop "a progression with a case-only twin is linked by its path"
rm -rf "$A"

exit $fail
